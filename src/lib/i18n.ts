const dicts: Record<Lang, Dict> = { ru, en };

export type TFunction = (key: TKey, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? ru[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

export function useLang(): Lang {
  return useData((s) => s.prefs.lang);
}

export function useT(): TFunction {
  const lang = useLang();
  return useCallback((key, vars) => translate(lang, key, vars), [lang]);
}

export function dateLocale(lang: Lang): Locale {
  return lang === 'ru' ? ruLocale : enUS;
}

export function detectLang(): Lang {
  if (typeof navigator === 'undefined') return 'ru';
  return navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'ru';
}

/** Russian plural helper: plural(5, ['задача', 'задачи', 'задач']). */
export function pluralRu(n: number, forms: [string, string, string]): string {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return forms[2];
  if (b > 1 && b < 5) return forms[1];
  if (b === 1) return forms[0];
  return forms[2];
}
